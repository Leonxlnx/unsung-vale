        const v = this._v.set(e.pos.x, e.pos.y + e.def.core * 1.75 + 0.55, e.pos.z).project(cam);
        if (v.z > 1 || Math.abs(v.x) > 1.05 || Math.abs(v.y) > 1.05) continue;
