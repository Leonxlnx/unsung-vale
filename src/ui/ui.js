// Interface: loading, title, HUD, pause, settings, credits and the ending card.
// Plain DOM over the canvas; no framework. Text is sentence case throughout.
import './ui.css';
import * as THREE from 'three';
import { TUNE } from '../game/player.js';
import creditsText from '../../CREDITS.md?raw';

const h = (html) => { const t = document.createElement('template'); t.innerHTML = html.trim(); return t.content.firstChild; };

const KEYS = [
  ['Move', 'W A S D'], ['Look', 'Mouse'], ['Sprint', 'Shift'], ['Jump', 'Space'], ['Dodge roll', 'Ctrl or C'],
  ['Strike', 'Left mouse'], ['Heavy strike', 'Right mouse'], ['Resonance pulse', 'F'], ['Lock on', 'Q'], ['Tune a spire', 'Hold E'], ['Pause', 'Esc'],
];

export class UI {
  constructor({ game, settings, apply }) {
    this.game = game; this.settings = settings; this.apply = apply;
    this.root = h(`<div id="ui">
      <div id="hud" class="screen">
        <div class="hurt"></div>
        <div class="objective"></div>
        <div class="boss"><div class="name"></div><div class="meter"><i></i></div></div>
        <div class="reticle"></div>
        <div class="vitals"><div class="meter health"><i></i></div><div class="meter stamina"><i></i></div></div>
        <div class="pulse"></div>
        <div class="prompt"><div class="key"><span></span></div><div class="text"></div></div>
        <div class="toast"></div>
        <div class="hints"></div>
        <div class="fps"></div>
      </div>
      <div id="home" class="screen">
        <div class="block">
          <h1>Unsung Vale</h1>
          <p class="sub">The valley has fallen silent. Wake its spires and let it sing again.</p>
          <div class="menu">
            <button class="primary" data-act="play"></button>
            <button data-act="new" hidden>New journey</button>
            <button data-act="settings">Settings</button>
            <button data-act="credits">Credits</button>
          </div>
        </div>
        <div class="foot">A demo. Everything you see is generated by code.</div>
      </div>
      <div id="pause" class="screen scrim"><div class="panel"><h2>Paused</h2><div class="menu">
        <button class="primary" data-act="resume">Resume</button><button data-act="settings">Settings</button><button data-act="title">Return to title</button>
      </div></div></div>
      <div id="settings" class="screen scrim"><div class="panel"><h2>Settings</h2>
        <div class="tabs"><button data-tab="graphics" class="on">Graphics</button><button data-tab="controls">Controls</button><button data-tab="audio">Audio</button></div>
        <div class="tabbody"></div><button class="back" data-act="back">Back</button></div></div>
      <div id="credits" class="screen scrim"><div class="panel"><h2>Credits</h2><div class="credits"></div><button class="back" data-act="back">Back</button></div></div>
      <div id="ending" class="screen"><div><h2>The Vale sings again</h2><p>Every spire is tuned. Thank you for playing.</p>
        <div class="menu"><button class="primary" data-act="continue">Keep exploring</button><button data-act="title">Return to title</button></div></div></div>
      <div id="fade"></div>
      <div id="loading" class="screen on"><div class="inner"><h1>Unsung Vale</h1><div class="bar"><i></i></div><p>Preparing the valley</p></div></div>
    </div>`);
    document.body.appendChild(this.root);
    const $ = (s) => this.root.querySelector(s);
    this.el = {
      loading: $('#loading'), loadBar: $('#loading .bar i'), loadText: $('#loading p'), home: $('#home'), hud: $('#hud'), pause: $('#pause'),
      settings: $('#settings'), credits: $('#credits'), ending: $('#ending'), fade: $('#fade'),
      health: $('.meter.health i'), stamina: $('.meter.stamina i'), objective: $('#hud .objective'), prompt: $('#hud .prompt'), promptKey: $('#hud .prompt .key'),
      promptKeyText: $('#hud .prompt .key span'), promptText: $('#hud .prompt .text'), boss: $('#hud .boss'), bossName: $('#hud .boss .name'), bossBar: $('#hud .boss .meter i'),
      pulse: $('#hud .pulse'), reticle: $('#hud .reticle'), hurt: $('#hud .hurt'), toast: $('#hud .toast'), hints: $('#hud .hints'), fps: $('#hud .fps'),
      tabBody: $('#settings .tabbody'), play: $('[data-act="play"]'), newGame: $('[data-act="new"]'),
    };
    this.el.hints.innerHTML = KEYS.slice(0, 8).map(([a, k]) => `<b>${k}</b><span>${a}</span>`).join('');
    this._renderCredits();
    this.tab = 'graphics'; this.returnTo = 'home';
    this._fpsAcc = 0; this._fpsN = 0;
    this._v = new THREE.Vector3();

    this.root.addEventListener('click', (e) => {
      const b = e.target.closest('button');
      if (!b) return;
      this.onSound?.('ui_click');
      const act = b.dataset.act, tab = b.dataset.tab;
      if (tab) { this.tab = tab; this._renderSettings(); return; }
      if (b.dataset.set) { this._set(b.dataset.set, b.dataset.val); return; }
      if (act === 'play') this._begin();
      if (act === 'new') { if (confirm('Start over? Your tuned spires will be forgotten.')) game.resetProgress(); }
      if (act === 'resume') game.resume();
      if (act === 'settings') { this.returnTo = game.state === 'paused' ? 'pause' : 'home'; this._renderSettings(); this.show('settings'); }
      if (act === 'credits') { this.returnTo = 'home'; this.show('credits'); }
      if (act === 'back') this.show(this.returnTo);
      if (act === 'title') { this._fadeThen(() => { game.toHome(); }); }
      if (act === 'continue') { this.el.ending.classList.remove('on'); game.start(); }
    });
    this.root.addEventListener('mouseover', (e) => { if (e.target.closest('button')) this.onSound?.('ui_hover'); });
    this.root.addEventListener('input', (e) => {
      const t = e.target;
      if (t.type === 'range') { this.settings.set(t.dataset.key, Number(t.value)); t.nextElementSibling.textContent = this._fmt(t.dataset.key, Number(t.value)); this.apply(); }
    });

    game.on((type, d) => this._onGame(type, d));
    this.el.objective.textContent = game.objective;
  }

  setLoading(p, text) { this.el.loadBar.style.transform = `scaleX(${p})`; if (text) this.el.loadText.textContent = text; }
  hideLoading() { this.el.loading.classList.remove('on'); this.show('home'); }

  show(name) {
    for (const k of ['home', 'pause', 'settings', 'credits']) this.el[k].classList.toggle('on', k === name);
    this.el.hud.classList.toggle('on', name === 'hud' || name === 'pause');
    if (name === 'home') { this.el.play.textContent = this.game.hasSave ? 'Continue' : 'Begin'; this.el.newGame.hidden = !this.game.hasSave; this.el.ending.classList.remove('on'); }
  }

  _fadeThen(fn) { this.el.fade.classList.add('on'); setTimeout(() => { fn(); this.el.fade.classList.remove('on'); }, 650); }

  _begin() {
    this.onSound?.('ui_open');
    this._fadeThen(() => {
      this.game.respawnAtCheckpoint();
      this.game.start();
      this.el.hints.classList.add('on');
      setTimeout(() => this.el.hints.classList.remove('on'), 14000);
    });
  }

  _onGame(type, d) {
    if (type === 'state') { if (d.state === 'playing') this.show('hud'); else if (d.state === 'paused') this.show('pause'); else if (d.state === 'home') this.show('home'); }
    if (type === 'objective') this.el.objective.textContent = d.text;
    if (type === 'boss') { this.el.boss.classList.toggle('on', !!d.enemy); if (d.enemy) this.el.bossName.textContent = d.enemy.def.name; }
    if (type === 'tuned') this.toast({ petal: 'The Petal Court sings', cantor: "Cantor's Rise sings", choir: 'The Choir sings' }[d.spire.id]);
    if (type === 'player' && d.type === 'hurt') { this.el.hurt.style.transition = 'none'; this.el.hurt.style.opacity = '1'; requestAnimationFrame(() => { this.el.hurt.style.transition = ''; this.el.hurt.style.opacity = '0'; }); }
    if (type === 'ending') setTimeout(() => { this.game.state = 'ending'; this.game.input.enabled = false; this.game.input.unlockPointer(); this.el.ending.classList.add('on'); }, 6500);
  }

  toast(text) {
    this.el.toast.textContent = text; this.el.toast.classList.add('on');
    clearTimeout(this._toastT); this._toastT = setTimeout(() => this.el.toast.classList.remove('on'), 4200);
  }

  // Per-frame HUD refresh.
  update(dt) {
    const g = this.game, p = g.player, el = this.el;
    if (g.state !== 'playing') return;
    el.health.style.transform = `scaleX(${p.health / TUNE.healthMax})`;
    el.stamina.style.transform = `scaleX(${p.stamina / TUNE.staminaMax})`;
    const pr = 1 - p.pulseTimer / TUNE.pulseCooldown;
    el.pulse.style.setProperty('--p', pr.toFixed(3)); el.pulse.classList.toggle('ready', pr >= 1);
    const lowHealth = p.health < 30 ? 0.55 * (1 - p.health / 30) : 0;
    if (!el.hurt.style.transition) el.hurt.style.opacity = String(lowHealth);
    if (g.prompt) {
      el.prompt.classList.add('on'); el.promptKeyText.textContent = g.input.usingPad ? 'X' : g.prompt.key; el.promptText.textContent = g.prompt.text;
      el.promptKey.style.setProperty('--p', Math.min(1, g.prompt.progress ?? 0).toFixed(3));
    } else el.prompt.classList.remove('on');
    if (g.boss) el.bossBar.style.transform = `scaleX(${Math.max(0, g.boss.hp / g.boss.def.hp)})`;
    const t = p.lockTarget;
    if (t) {
      const v = this._v.set(t.pos.x, t.pos.y + t.def.core, t.pos.z).project(g.pipe.camera);
      el.reticle.classList.toggle('on', v.z < 1);
      el.reticle.style.left = `${(v.x * 0.5 + 0.5) * 100}%`; el.reticle.style.top = `${(-v.y * 0.5 + 0.5) * 100}%`;
    } else el.reticle.classList.remove('on');
    if (this.settings.get('showFps')) {
      this._fpsAcc += dt; this._fpsN++;
      if (this._fpsAcc > 0.5) { el.fps.textContent = `${Math.round(this._fpsN / this._fpsAcc)} fps`; this._fpsAcc = 0; this._fpsN = 0; }
    } else if (el.fps.textContent) el.fps.textContent = '';
  }

  // --- settings panel ---
  _fmt(key, v) { return key === 'fov' ? `${Math.round(v)}°` : key === 'sensitivity' ? `${v.toFixed(2)}×` : `${Math.round(v * 100)}%`; }
  _set(key, val) {
    const cur = this.settings.get(key);
    const v = val === 'toggle' ? !cur : isNaN(Number(val)) ? val : Number(val);
    this.settings.set(key, v); this.apply(); this._renderSettings();
  }
  _renderSettings() {
    const s = this.settings.values;
    this.root.querySelectorAll('.tabs button').forEach((b) => b.classList.toggle('on', b.dataset.tab === this.tab));
    const seg = (key, opts) => `<div class="seg">${opts.map(([v, l]) => `<button data-set="${key}" data-val="${v}" class="${String(s[key]) === String(v) ? 'on' : ''}">${l}</button>`).join('')}</div>`;
    const slider = (key, min, max, step) => `<div class="slider"><input type="range" data-key="${key}" min="${min}" max="${max}" step="${step}" value="${s[key]}"><output>${this._fmt(key, s[key])}</output></div>`;
    const toggle = (key) => `<button class="toggle ${s[key] ? 'on' : ''}" data-set="${key}" data-val="toggle" aria-pressed="${!!s[key]}"></button>`;
    const row = (label, control, note = '') => `<div class="row"><div><label>${label}</label>${note ? `<small>${note}</small>` : ''}</div>${control}</div>`;
    let html = '';
    if (this.tab === 'graphics') {
      html = row('Quality', seg('preset', [['low', 'Low'], ['medium', 'Medium'], ['high', 'High'], ['ultra', 'Ultra']]), s.preset === 'custom' ? 'Custom' : '')
        + row('Render scale', slider('renderScale', 0.4, 1, 0.01), 'Lower is faster; the image is sharpened back up')
        + row('Object shadows', toggle('shadows')) + row('Light shafts and mist', toggle('volumetrics'))
        + row('Ground cover', slider('cover', 0.4, 1, 0.05), 'How far grass and flowers reach')
        + row('Field of view', slider('fov', 45, 80, 1)) + row('Show frame rate', toggle('showFps'));
    } else if (this.tab === 'controls') {
      html = row('Look sensitivity', slider('sensitivity', 0.3, 2.5, 0.05)) + row('Invert vertical look', toggle('invertY'))
        + `<div class="keys" style="margin-top:16px">${KEYS.map(([a, k]) => `<span>${a}</span><span>${k}</span>`).join('')}</div>`;
    } else {
      html = row('Master volume', slider('master', 0, 1, 0.01)) + row('Music', slider('music', 0, 1, 0.01)) + row('Effects', slider('sfx', 0, 1, 0.01));
    }
    this.el.tabBody.innerHTML = html;
  }

  _renderCredits() {
    // A light pass over the Markdown: headings and plain lines.
    const lines = creditsText.split(/\r?\n/).filter((l) => l.trim() && !l.startsWith('|--'));
    const esc = (s) => s.replace(/[<>&]/g, (c) => ({ '<': '&lt;', '>': '&gt;', '&': '&amp;' }[c]));
    const html = lines.map((l) => (l.startsWith('#') ? `<h3>${esc(l.replace(/^#+\s*/, ''))}</h3>` : `<p>${esc(l.replace(/^[-*]\s*/, '').replace(/\[([^\]]+)\]\([^)]+\)/g, '$1').replace(/[*_`|]/g, ' '))}</p>`)).join('');
    this.root.querySelector('#credits .credits').innerHTML = `<p>Design, code, models and textures are procedural and original to this project. Music and sound come from the artists below.</p>${html}`;
  }
}
